    private void buttonRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonRegistrarActionPerformed
        // Validar
        String errores = validar();
        if(errores.isEmpty()) {
            // Se encripta la contraseña
            String hashPass = HashService.sha1Hash(
                fieldPass1.getText()
            );
            // Se crea el objeto usuario
            Usuario usuario = new Usuario(
                fieldNombre.getText(),
                fieldUsuario.getText(),
                hashPass,
                imagePath,
                false
            );
            // Se agrega a la lista
            users.add(usuario);
            // Se escribe en el archivo
            if(JsonService.writeUsers(users)) {
                JOptionPane.showMessageDialog(null,"Registrado");
                dispose();
            } else {
                JOptionPane.showMessageDialog(null,"Error al registrar");
            }
        } else {
            JOptionPane.showMessageDialog(null,errores);
        }
    }//GEN-LAST:event_buttonRegistrarActionPerformed

    private String validar() {
        String errores = "";
        JTextField [] fields = {
            fieldNombre, fieldUsuario
        };
        JPasswordField [] passwords = {
            fieldPass1, fieldPass2
        };
        for(JTextField field : fields) {
            if(field.getText().trim().isEmpty()) {
                errores += "\nCampo vacio";
                field.setBackground(Color.yellow);
            }
        }
        for(JPasswordField field : passwords) {
            if(field.getText().trim().isEmpty()) {
                errores += "\nContraseña vacia";
                field.setBackground(Color.yellow);
            }
        }
        if(!fieldPass1.getText().equals(fieldPass2.getText())) {
            errores += "\nLas contraseñas no coinciden";
        }
        return errores;
    }
    
