    private void buttonAccederActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonAccederActionPerformed
        String usr = fieldUsuario.getText().trim();
        String pass = fieldPassword.getText().trim();
        pass = HashService.sha1Hash(pass);
        
        Usuario encontrado = null;
        for(Usuario obj : users) {
            if(obj.getUsuario().equals(usr) && obj.getContrasenia().equals(pass)) {
                encontrado = obj;
                break;
            }
        }
        
        if(encontrado != null) {
            // Se encontro el usuario
            if(!encontrado.isActivo()) {
                JOptionPane.showMessageDialog(null,"Usuario bloqueado");
                return;
            }
            
            if(encontrado.isAdmin()) {
                new MainFrame(encontrado, users, sales).setVisible(true);
            } else {
                new ClientFrame(encontrado, users, sales).setVisible(true);
            }
        } else {
            JOptionPane.showMessageDialog(null,"Usuario y/o contraseña incorrectos");
        }
        
    }//GEN-LAST:event_buttonAccederActionPerformed

