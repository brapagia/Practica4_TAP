    private void cargaUsuarios() {
        DefaultTableModel model = (DefaultTableModel) 
            jTable1.getModel();
        
        model.setRowCount(0);
        for(Usuario obj : usuarios) {
            model.addRow(new Object[]{
                obj.getIdUsuario(),
                obj.getNombre(),
                obj.getUsuario()
            });
        }
    }
    
