    private void jTable1PropertyChange(java.beans.PropertyChangeEvent evt) {//GEN-FIRST:event_jTable1PropertyChange
        int index = jTable1.getSelectedRow();
        if(index < 0) return;
        
        buttonBloqueo.setEnabled(index > -1);
        
        if(usuarios.get(index).isActivo()) {
            buttonBloqueo.setText("Bloquear usuario");
            buttonBloqueo.setForeground(Color.red);
        } else {
            buttonBloqueo.setText("Desbloquear usuario");
            buttonBloqueo.setForeground(Color.green);
        }
    }//GEN-LAST:event_jTable1PropertyChange

    private void buttonBloqueoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonBloqueoActionPerformed
        int index = jTable1.getSelectedRow();
        if(index < 0) return;
        
        if(usuarios.get(index).isAdmin()) {
            if(
                JOptionPane.showConfirmDialog(
                    null,
                    "El usuario es administrador. ¿Desea continuar?"
                ) != JOptionPane.YES_OPTION
            ) return;
        }
        
        usuarios.get(index).setActivo(
            !usuarios.get(index).isActivo()
        );
        
        JsonService.writeUsers(usuarios);
        
        cargaUsuarios();
    }//GEN-LAST:event_buttonBloqueoActionPerformed

