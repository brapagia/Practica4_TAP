    private void mostrarVentas() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        
        Double total = 0.0;
        for(Venta v : ventas) {
            model.addRow(new Object[]{
                v.getProducto().getNombre(),
                v.getCantidad(),
                v.getTotal(),
                v.getUsuario().getNombre(),
                v.getFecha()
            });
            total += v.getTotal();
        }
        labelTotal.setText("TOTAL: $" + total);
    }

