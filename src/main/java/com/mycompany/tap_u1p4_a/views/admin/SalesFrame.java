    private void buttonExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonExportarActionPerformed
        jFileChooser1.setSelectedFile(new File("ventas.csv"));
        if(jFileChooser1.showSaveDialog(null) == JFileChooser.APPROVE_OPTION) {
            File ruta = jFileChooser1.getSelectedFile();
            // Se recorre la tabla
            String csv = "Producto,Cantidad,Total,Usuario,Fecha\n";
            for (int i = 0; i < jTable1.getRowCount(); i++) {
                csv += jTable1.getValueAt(i, 0) + ",";
                csv += jTable1.getValueAt(i, 1) + ",";
                csv += jTable1.getValueAt(i, 2) + ",";
                csv += jTable1.getValueAt(i, 3) + ",";
                csv += jTable1.getValueAt(i, 4) + "\n";
            }
            // Se escribe el archivo
            try {
                Path path = Path.of(
                    ruta.getAbsolutePath()
                );
                Files.writeString(path, csv);
                
                JOptionPane.showMessageDialog(null,"Exportado");
            } catch (Exception e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(null,"Error al exportar");
            }
        }
    }//GEN-LAST:event_buttonExportarActionPerformed

