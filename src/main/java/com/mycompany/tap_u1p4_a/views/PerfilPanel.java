    public void setUser(Usuario user) {
        this.user = user;
        
        labelNombre.setText(user.getNombre());
        labelUsuario.setText(user.getUsuario());
        
        loadImage();
    }
    
    private void loadImage() {
        if(user.getFotoPerfil() == null || user.getFotoPerfil().isEmpty()) {
            return;
        }
        
        try {
            panelImage1.setIcon(
                new ImageIcon(user.getFotoPerfil())
            );
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

