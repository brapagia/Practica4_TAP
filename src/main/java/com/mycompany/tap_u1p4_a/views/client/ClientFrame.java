    private void mostrarComprar() {
        jDesktopPane1.removeAll();
        
        ProductosInternalFrame internal = new ProductosInternalFrame(usuario, productosActivos(), ventas);
        jDesktopPane1.add(internal);
        internal.setVisible(true);
    }
    
    private ArrayList<Producto> productosActivos() {
        ArrayList<Producto> activos = new ArrayList<>();
        for(Producto p : productos) {
            if(p.isActivo()) activos.add(p);
        }
        return activos;
    }
    
