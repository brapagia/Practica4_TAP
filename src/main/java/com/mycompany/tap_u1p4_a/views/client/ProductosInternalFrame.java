    private void buttonLeftActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonLeftActionPerformed
        if(indice > 0) {
            indice--;
        } else {
            // Vamos al ultimo indice
            indice = productos.size()-1;
        }
        mostrarProducto(indice);
    }//GEN-LAST:event_buttonLeftActionPerformed

    private void buttonRightActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonRightActionPerformed
        if(indice < productos.size()-1) {
            indice++;
        } else {
            // Vamos al primer indice
            indice = 0;
        }
        mostrarProducto(indice);
    }//GEN-LAST:event_buttonRightActionPerformed

    private void buttonComprarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonComprarActionPerformed
        String strCantidad = JOptionPane.showInputDialog(
            "¿Qué cantidad de " + productos.get(indice).getNombre() +
            " vas a comprar?"
        );
        try {
            int cantidad = Integer.parseInt(strCantidad);
            if(cantidad > 0) {
                Venta venta = new Venta();
                venta.setCantidad(cantidad);
                venta.setProducto(productos.get(indice));
                venta.setUsuario(usuario);
                venta.setTotal(cantidad * productos.get(indice).getPrecio());
                
                ventas.add(venta);
                JsonService.writeSales(ventas);
                JOptionPane.showMessageDialog(null,"Venta realizada!");
                
                mostrarHistorial();
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null,"Cantidad invalida");
        }
    }//GEN-LAST:event_buttonComprarActionPerformed

    private void mostrarHistorial() {
        jTextArea1.setText("");
        for(Venta v : ventas) {
            if(v.getUsuario().getIdUsuario().equals(usuario.getIdUsuario())) {
                jTextArea1.append(
                    v.getFecha() + ":\n" +
                    v.getProducto().getNombre() +
                    "(" + v.getCantidad()+")... $" +
                    v.getTotal()
                );
                jTextArea1.append("\n\n");
            }
        }
    }

